"""Makes src/backend/xdg-public-names.c: every name xdg-user-dirs has given
the public share folder (XDG_PUBLICSHARE_DIR, "Public" in English), in every
language, through the whole history of its translations, so a folder named
in 2007 is still known when no installed catalog has that name any more.

    python3 -I tools/xdg-public-names.py <xdg-user-dirs checkout> > src/backend/xdg-public-names.c

The checkout is a full clone (not shallow) of
https://gitlab.freedesktop.org/xdg/xdg-user-dirs.git. Only translated,
non-fuzzy entries count. The names on the machine itself (the installed
catalogs, Ubuntu's language packs among them) are read at run time; this
table is what the project knows besides."""
import collections
import re
import subprocess
import sys


def git(repo, *args):
    return subprocess.run(['git', '-C', repo, *args], capture_output=True, text=True,
                          errors='replace', check=True).stdout


ENTRY = re.compile(r'msgid "Public"\n((?:msgstr "(?:[^"\\]|\\.)*"\n?)(?:"(?:[^"\\]|\\.)*"\n?)*)', re.M)


def names_in(text):
    """The translations of "Public" in one po file, without fuzzy or old ones."""
    for m in ENTRY.finditer(text):
        start = text.rfind('\n\n', 0, m.start())
        block = text[start:m.end()]
        if '#, fuzzy' in block or '#~' in block:
            continue
        value = ''.join(re.findall(r'"((?:[^"\\]|\\.)*)"', m.group(1)))
        if value:
            yield value


def c_string(s):
    """A C string literal; the source is UTF-8, so names stay readable."""
    if any(ord(ch) < 0x20 or ch == '\x7f' for ch in s):
        sys.exit('a control character in %r' % s)
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'


def main():
    if len(sys.argv) != 2:
        sys.exit('usage: xdg-public-names.py <xdg-user-dirs checkout>')
    repo = sys.argv[1]
    head = git(repo, 'log', '-1', '--format=%H %as').split()
    current = {f.split('/')[-1][:-3] for f in git(repo, 'ls-tree', '--name-only', 'HEAD', 'po/').split()
               if f.endswith('.po')}
    files = {f for f in git(repo, 'log', '--all', '--name-only', '--format=', '--', 'po/').split()
             if f.endswith('.po')}
    found = collections.defaultdict(collections.OrderedDict)  # lang -> name -> first seen
    last = {}                                                  # lang -> name at HEAD
    for f in sorted(files):
        lang = f.split('/')[-1][:-3]
        revs = [r for r in git(repo, 'log', '--all', '--format=%H %as', '--', f).split('\n') if r]
        for rev in reversed(revs):
            h, date = rev.split()
            try:
                text = git(repo, 'show', '%s:%s' % (h, f))
            except subprocess.CalledProcessError:
                continue  # removed in this commit
            for name in names_in(text):
                found[lang].setdefault(name, date)
        if lang in current:
            now = list(names_in(git(repo, 'show', 'HEAD:' + f)))
            if now:
                last[lang] = now[0]
    print('/* SPDX-License-Identifier: GPL-3.0-only */')
    print('/* Generated by tools/xdg-public-names.py from xdg-user-dirs %s (%s).' % (head[0][:12], head[1]))
    print(' * Do not edit by hand: run the tool again. */')
    print('#include "xdg-public-names.h"')
    print()
    print('const gaudit_xdg_public_name gaudit_xdg_public_names[] = {')
    print('    { "", "Public", "", 1 },  /* the English name, and every untranslated language */')
    for lang in sorted(found):
        for name, date in found[lang].items():
            print('    { %s, %s, "%s", %d },' % (c_string(lang), c_string(name), date,
                                                 1 if last.get(lang) == name else 0))
    print('};')
    print()
    print('const unsigned gaudit_xdg_public_names_count =')
    print('    sizeof gaudit_xdg_public_names / sizeof gaudit_xdg_public_names[0];')


if __name__ == '__main__':
    main()
